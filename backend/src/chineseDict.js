export function translateBrandId(brandId) {
  const entry = BRAND_CATALOG[brandId];
  if (!entry) return null;
  return BRAND_LATIN_MAP[entry.name] ?? entry.name;
}

export function getBrandNameRaw(brandId) {
  return BRAND_CATALOG[brandId]?.name ?? null;
}

// --- Ленивая загрузка seriesid -> название (车系, модельный ряд) ---
//
// В отличие от брендов (их фиксированные ~400 - выкачаны разом выше),
// моделей у каждого бренда десятки, и тянуть все ~400 брендов сразу ради
// одной модели, которая, возможно, вообще не встретится в объявлениях -
// расточительно. Вместо этого грузим страницу конкретного бренда (она
// отдаёт СРАЗУ ВСЕ его серии одним запросом - см. SERIES_RE ниже) только
// когда реально встретили новый brandId в списке Che168, и держим
// результат в памяти процесса до перезапуска - модельные ряды не меняются
// в масштабе недель/месяцев, гонять этот запрос при каждом sync незачем.
import axios from 'axios';

const seriesCache = new Map(); // brandId -> Map(seriesId -> name) | null (после неудачной попытки)

// Пример разметки страницы бренда (car.autohome.com.cn/price/list-...html):
// data-event-evextends='{"typeid":0,"seriesid":802,"state":0}' href="/price/series-802.html#..." target="_self" class="font-bold">发现</a>
const SERIES_RE = /"seriesid":(\d+)[^}]*\}'[^>]*class="font-bold">([^<]+)</g;

async function fetchBrandSeries(brandId) {
  const entry = BRAND_CATALOG[brandId];
  if (!entry) return null;
  const url = `https://car.autohome.com.cn${entry.path}`;
  const { data } = await axios.get(url, {
    responseType: 'arraybuffer',
    timeout: 15000,
    headers: {
      'User-Agent':
        'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36',
    },
  });
  // car.autohome.com.cn отдаёт страницы в GBK/GB2312, а не UTF-8 (в отличие
  // от www.autohome.com.cn) - декодируем явно, иначе кириллица/иероглифы
  // побьются. TextDecoder('gbk') - штатная возможность Node (ICU), доп.
  // зависимость (iconv-lite и т.п.) не нужна.
  const html = new TextDecoder('gbk').decode(data);
  const map = new Map();
  let m;
  while ((m = SERIES_RE.exec(html))) {
    const id = Number(m[1]);
    if (!map.has(id)) map.set(id, m[2].trim());
  }
  return map;
}

export async function getSeriesName(brandId, seriesId) {
  if (!seriesCache.has(brandId)) {
    try {
      seriesCache.set(brandId, await fetchBrandSeries(brandId));
    } catch (e) {
      console.warn(
        `[chineseDict] не удалось загрузить модельный ряд бренда ${brandId} (${getBrandNameRaw(brandId) ?? '?'}): ${e.message}`
      );
      // Не повторяем запрос на каждое объявление в рамках этого же прогона
      // sync при сбое сети/car.autohome.com.cn - следующий процесс попробует
      // снова (кэш живёт только в памяти текущего процесса).
      seriesCache.set(brandId, null);
      return null;
    }
  }
  const map = seriesCache.get(brandId);
  return map ? map.get(Number(seriesId)) ?? null : null;
}
